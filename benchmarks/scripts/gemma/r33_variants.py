def _alpha_label(index: int) -> str:
    chars: list[str] = []
    value = index
    while True:
        value, remainder = divmod(value, 26)
        chars.append(chr(ord("a") + remainder))
        if value == 0:
            return "".join(reversed(chars))
        value -= 1


def _build_alpha_control_recipients() -> tuple[str, ...]:
    recipients: list[str] = []
    cursor = 0
    while len(recipients) < len(RECIPIENTS):
        recipient = _alpha_label(cursor)
        cursor += 1
        if recipient.casefold() not in _ALPHA_BLOCKLIST:
            recipients.append(recipient)
    return tuple(recipients)


